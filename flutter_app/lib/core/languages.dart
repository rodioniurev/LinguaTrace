/// Display name for [code] in the UI language ([localeCode], e.g. 'ru').
/// Falls back: localized → English → the raw code.
String localizedLangName(String code, String localeCode) {
  if (localeCode == 'ru') {
    final ru = kLanguagesRu[code] ??
        kLanguagesRu[code.length >= 2 ? code.substring(0, 2) : code];
    if (ru != null) return ru;
  }
  return kLanguages[code] ??
      kLanguages[code.length >= 2 ? code.substring(0, 2) : code] ??
      code;
}

